/** A question's state as the page marks it: `💬`, `💬 🤷`, `🔒` or `✅`. */
function stateGlyph(state: QuestionState, preference: boolean): string {
  if (state === "blocked") return VANTAGE_OQ_STATUS.blocked;
  if (state === "answered") return VANTAGE_OQ_STATUS.settled;
  return preference
    ? `${VANTAGE_OQ_STATUS.open} ${VANTAGE_OQ_PREFERENCE}`
    : VANTAGE_OQ_STATUS.open;
}

/**
 * One question: where its item starts, its state and its title, so a reader
 * can open the file at the line and read the question there.
 */
function questionLine(index: PlanningIndex, ref: QuestionRef): string {
  const q = questionFor(index, ref);
  if (q === undefined) return `${ref.path}:${ref.line}  ${ref.id ?? ""}`;
  return `${q.path}:${q.unitLine}  ${stateGlyph(q.state, q.preference)} ${oneLine(q.title)}`;
}

/** A document, with the badge a link to it would carry. */
function documentLine(index: PlanningIndex, path: string): string {
  const badge = badgeFor(index, "", { path, fragment: null });
  return badge === null ? path : `${path}  [${badgeText(badge)}]`;
}

function bytes(n: number): string {
  return `${n.toLocaleString("en-US")} bytes`;
}

/** A heading with its count, then one indented line per entry. */
function block(title: string, lines: readonly string[]): string | null {
  if (lines.length === 0) return null;
  return [
    `${title} (${lines.length.toLocaleString("en-US")})`,
    ...lines.map((line) => `  ${line}`),
  ].join("\n");
}

/**
 * One of the page's sections: its title and count, its explanation line
 * unindented beneath, so only an entry is ever indented, then its entries.
 *
 * On the page "you" is the person reading it; an agent reads this output, so
 * a section whose actor is `you` says whom it means — *Needs you (4) · for
 * the human* — and an agent does not take "Rule each" as addressed to it.
 */
function section(
  id: PlanningSectionId,
  sections: PlanningSections,
  lines: readonly string[],
): string | null {
  if (lines.length === 0) return null;
  const forWhom =
    PLANNING_SECTION_GUIDE[id].actor === "you" ? " · for the human" : "";
  return [
    `${PLANNING_SECTION_TITLES[id]} (${lines.length.toLocaleString("en-US")})${forWhom}`,
    sectionExplanation(id, sections),
    ...lines.map((line) => `  ${line}`),
  ].join("\n");
}

/** `1 needs you`, `4 need you`. */
function needsYouCount(n: number): string {
  return `${n.toLocaleString("en-US")} ${n === 1 ? "needs" : "need"} you`;
}

/**
 * One line of the Roadmaps block: the path, then what it gives or why not. A
 * `done` roadmap was read, and its links are in the JSON, so it is said to be
 * ignored rather than not read; every other state is one the file was not
 * read in.
 */
function roadmapLine(roadmap: PlanningRoadmap, chosen: string | null): string {
  if (roadmap.state === "done") {
    return `${roadmap.path}  ignored: ${ROADMAP_STATE_PHRASES.done}`;
  }
  if (roadmap.state !== "routes") {
    return `${roadmap.path}  not read: ${ROADMAP_STATE_PHRASES[roadmap.state]}`;
  }
  const line = `${roadmap.path}  ${needsYouCount(roadmap.needsYouCount)}`;
  return roadmap.path === chosen ? `${line}  (chosen)` : line;
}

/**
 * The page's sections in page order, each hidden when empty and explained
 * under its heading, with the notices where the page shows them; a line
 * naming `--request` when an agent section has entries; then the chosen
 * roadmap's source with a badge in brackets after each badged link. With two
 * or more roadmaps, in any state, a Roadmaps block lists them before Needs
 * you; with one or none there is no such block.
 *
 * Under a filter, `sections` are the filtered ones and `filter.head` is
 * `filterHead`'s, printed first (§13.4). Everything after it is the same
 * layout over the filtered sections: *Nothing needs you* in its filtered form,
 * the Roadmaps block with the filtered counts, and a `--request` line that
 * carries the filter, shell-quoted. The roadmap's source is the index's, and
 * unchanged.
 *
 * A filter that keeps no entry has `filter.nothingMatches`, the page's words
 * for it: *Nothing matches* and its reason line stand where the sections
 * would, after the Roadmaps block, and *Nothing this filter keeps needs you*
 * is not printed, as the page does not show it.
 */
function renderText(
  project: ScannedProject,
  sections: PlanningSections,
  filter: {
    head: string;
    canonical: string;
    nothingMatches: string | null;
  } | null = null,
): string {
  const { index } = project;
  const { config } = index;
  const blocks: (string | null)[] = [];
  if (filter !== null) blocks.push(filter.head);
  const nothingMatches = filter?.nothingMatches ?? null;

  const notices: string[] = [];
  if (sections.nothingNeedsYou && nothingMatches === null) {
    notices.push(
      filter === null
        ? PLANNING_NOTICES.nothingNeedsYou
        : PLANNING_NOTICES.nothingFilteredNeedsYou,
    );
  }
  const roadmapNotice = PLANNING_NOTICES.roadmapNotice(
    config,
    sections.roadmaps,
  );
  if (roadmapNotice !== null) notices.push(roadmapNotice);
  if (sections.onOtherRoadmaps.length > 0) {
    notices.push(
      `${PLANNING_NOTICES.otherRoadmaps(sections.onOtherRoadmaps.length)} Choose one with --roadmap <path>.`,
    );
  }
  if (notices.length > 0) blocks.push(notices.join("\n"));

  if (sections.roadmaps.length >= 2) {
    blocks.push(
      block(
        "Roadmaps",
        sections.roadmaps.map((r) => roadmapLine(r, sections.chosenRoadmap)),
      ),
    );
  }
  // Every section below is empty, and not printed.
  if (nothingMatches !== null) blocks.push(nothingMatches);

  blocks.push(
    section(
      "needs-you",
      sections,
      sections.needsYou.map((ref) => {
        const line = questionLine(index, ref);
        return ref.heading === null ? line : `${line}  (${ref.heading})`;
      }),
    ),
  );
  blocks.push(
    section(
      "unrouted",
      sections,
      (sections.unrouted ?? []).map((ref) => questionLine(index, ref)),
    ),
  );
  blocks.push(
    section(
      "waiting",
      sections,
      sections.waiting.map((entry) =>
        entry.kind === "question"
          ? questionLine(index, entry.question)
          : `${entry.path}  blocked on ${entry.waitingOn.map(dependsOnLabel).join(", ")}`,
      ),
    ),
  );

  if (!sections.stagesDeclared) blocks.push(PLANNING_NOTICES.noStages);
  for (const [id, paths] of [
    ["ready", sections.ready],
    ["graduate", sections.graduate],
    ["disagrees", sections.disagrees],
  ] as const) {
    blocks.push(
      section(
        id,
        sections,
        (paths ?? []).map((path) => documentLine(index, path)),
      ),
    );
  }

  blocks.push(
    section(
      "skipped",
      sections,
      sections.skipped.map(
        (s) =>
          `${s.path}  ${bytes(s.size)}, over max-file-bytes (${bytes(config.maxFileBytes)})`,
      ),
    ),
  );
  blocks.push(
    section(
      "could-not-read",
      sections,
      sections.unreadable.map((u) => `${u.path}  ${u.reason}`),
    ),
  );
  // What an agent's sections ask for is a command away; say which.
  if (agentSectionsWithEntries(sections).length > 0) {
    blocks.push(
      filter === null
        ? "Agent requests: vantage-check index --request"
        : `Agent requests: vantage-check index --request --filter ${shellQuote(filter.canonical)}`,
    );
  }

  const roadmap =
    sections.chosenRoadmap === null
      ? undefined
      : findDocument(index, sections.chosenRoadmap);
  const source =
    roadmap === undefined ? undefined : project.sources.get(roadmap.path);
  if (roadmap !== undefined && source !== undefined) {
    blocks.push(
      `Roadmap: ${roadmap.path}\n\n${badged(index, roadmap.path, roadmap.links, source).replace(/\n+$/, "")}`,
    );
  }

  return `${blocks.filter((b) => b !== null).join("\n\n")}\n`;
}

/** `source`, with ` [<badge>]` inserted just past every link that has one. */
function badged(
  index: PlanningIndex,
  from: string,
  links: PlanningIndex["documents"][number]["links"],
  source: string,
): string {
  const inserts = links
    .map((link) => {
      const badge = badgeFor(index, from, {
        path: link.target,
        fragment: link.fragment,
      });
      return badge === null
        ? null
        : { at: link.endOffset, text: ` [${badgeText(badge)}]` };
    })
    .filter((insert) => insert !== null)
    .sort((a, b) => b.at - a.at);
  let out = source;
  for (const { at, text } of inserts) {
    out = `${out.slice(0, at)}${text}${out.slice(at)}`;
  }
  return out;
}
